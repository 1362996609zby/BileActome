#!/usr/bin/env python3
"""Extract BileActome HMM hit protein sequences from MAG/WGS results.

The script scans family-specific hmmsearch outputs generated by
run_hmmsearch_batch.py and writes hit FASTA files under each family directory.
"""

from __future__ import annotations

import argparse
import logging
import sys
from pathlib import Path

def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Extract protein sequences passing the HMMER tblout E-value threshold."
    )
    parser.add_argument(
        "--result-dir",
        required=True,
        type=Path,
        help="Result directory generated by run_hmmsearch_batch.py.",
    )
    parser.add_argument(
        "--protein-dir",
        required=True,
        type=Path,
        help="Directory containing Prodigal-predicted .faa files.",
    )
    parser.add_argument(
        "--evalue",
        type=float,
        default=1e-3,
        help="Full-sequence E-value threshold for HMMER tblout hits. Default: 1e-3.",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Overwrite existing non-empty hit FASTA outputs.",
    )
    parser.add_argument(
        "--log-file",
        type=Path,
        default=None,
        help="Optional log file. Default: <result-dir>/extract_hits_from_fasta.log.",
    )
    return parser.parse_args()


def setup_logging(log_file: Path) -> None:
    log_file.parent.mkdir(parents=True, exist_ok=True)
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s [%(levelname)s] %(message)s",
        handlers=[
            logging.StreamHandler(sys.stdout),
            logging.FileHandler(log_file, mode="a", encoding="utf-8"),
        ],
    )


def nonempty(path: Path) -> bool:
    return path.exists() and path.stat().st_size > 0


def parse_tblout(tbl_file: Path, evalue_threshold: float) -> set[str]:
    hits: set[str] = set()
    with tbl_file.open() as handle:
        for line in handle:
            if line.startswith("#"):
                continue
            fields = line.strip().split()
            if len(fields) < 5:
                continue
            try:
                full_evalue = float(fields[4])
            except ValueError:
                continue
            if full_evalue <= evalue_threshold:
                hits.add(fields[0])
    return hits


def iter_fasta_records(fasta_file: Path):
    header = None
    seq_lines: list[str] = []
    with fasta_file.open() as handle:
        for line in handle:
            line = line.rstrip("\n")
            if line.startswith(">"):
                if header is not None:
                    yield header, seq_lines
                header = line
                seq_lines = []
            else:
                seq_lines.append(line)
        if header is not None:
            yield header, seq_lines


def extract_sequences(protein_file: Path, hit_ids: set[str], output_file: Path) -> int:
    total = 0
    output_file.parent.mkdir(parents=True, exist_ok=True)
    with output_file.open("w") as out_handle:
        for header, seq_lines in iter_fasta_records(protein_file):
            record_id = header[1:].split(None, 1)[0]
            if record_id in hit_ids:
                out_handle.write(header + "\n")
                out_handle.write("\n".join(seq_lines) + "\n")
                total += 1
    return total


def main() -> None:
    args = parse_args()
    result_dir = args.result_dir.resolve()
    protein_dir = args.protein_dir.resolve()
    log_file = (args.log_file or result_dir / "extract_hits_from_fasta.log").resolve()
    setup_logging(log_file)

    if not result_dir.is_dir():
        raise SystemExit(f"Result directory not found: {result_dir}")
    if not protein_dir.is_dir():
        raise SystemExit(f"Protein directory not found: {protein_dir}")

    tbl_files = sorted(result_dir.glob("*/hmmsearch/*.tbl"))
    if not tbl_files:
        raise SystemExit(f"No HMMER .tbl files found under {result_dir}/*/hmmsearch/")

    processed = 0
    missing_proteins = 0
    for tbl_file in tbl_files:
        family = tbl_file.parent.parent.name
        sample = tbl_file.stem
        protein_file = protein_dir / f"{sample}.faa"
        output_file = tbl_file.parent / "hits" / f"{sample}_hits.fasta"

        if nonempty(output_file) and not args.force:
            logging.info("Skip existing hit FASTA: %s", output_file)
            continue
        if not nonempty(protein_file):
            missing_proteins += 1
            logging.warning("Protein file missing or empty for %s: %s", sample, protein_file)
            continue

        hit_ids = parse_tblout(tbl_file, args.evalue)
        total = extract_sequences(protein_file, hit_ids, output_file)
        logging.info("%s | %s: extracted %d hits", family, sample, total)
        processed += 1

    logging.info(
        "Completed hit extraction for %d tbl files; missing protein files: %d.",
        processed,
        missing_proteins,
    )


if __name__ == "__main__":
    main()
